"use strict";

// durable-turns ASAR patch.
//
// Codex Desktop ties the lifetime of a turn to the lifetime of a UI client.
// Every automatic interrupt path in the upstream bundles encodes one
// assumption: nobody is watching, so stop the work. That assumption is inverted
// for the OpenCodex web deployment, where many concurrent browser viewers plus
// background and headless sessions are the normal case and losing a viewer is
// routine rather than exceptional. Measured on the 235.t production box, the
// gateway logged 888 orphaned app-host relays against only 470 reattachments,
// and one lost viewer took down 15 threads inside a single second, because a
// plain interrupt cascades to the whole subagent tree. The turn itself runs in
// the long-lived app-server process, so a viewer going away is not a reason to
// stop working.
//
// Why this file no longer contains an anchor string.
//
// The previous implementation anchored on exact minified strings inside
// fixed-name files (main-*.js, app-initial-*.js). On 2026-10-08 the 241.t
// fleet moved from upstream 26.908.40834 to 26.1002.52244, roughly 94 releases,
// and every anchor went to zero: upstream re-chunked the bundle, moving the
// main-process code from main-DaMR-wdT.js into bootstrap-*.js and the webview
// logic from app-initial-*.js into app-shared-*.js. What did not drift is the
// symbol surface: interruptConversationSelf, discardConversationFromCache,
// shouldKeepConversationLoaded and interruptSubagentDescendants all survived
// 94 releases untouched. Only file names and minified locals rotate.
//
// So the architecture is:
//   1. scan every chunk under .vite/build and webview/assets and pick the
//      carriers by the symbols they hold -- no file name is ever matched,
//   2. locate each rule by structural signature (function head, branch shape,
//      call sequence) inside its region -- no bare string anchor,
//   3. rewrite, then assert the terminal state: the old shape gone and the new
//      shape present, per rule, per carrier,
//   4. --check reports BOUND / DRIFTED / REMOVED per rule with a source excerpt
//      of the area, so drift is judged by reading a few hundred bytes instead
//      of grepping a bundle with 19k files.
//
// The rules themselves are data: signatures.json, generated by
// signatures.gen.js. ciPolicy stays required-upstream, so an unbound or
// ambiguous rule fails the build instead of shipping a half-applied patch.

const fs = require("node:fs");
const path = require("node:path");

const { execFileSync } = require("node:child_process");

const {
  BASELINE_SUFFIX: SCRATCH_BASELINE_SUFFIX,
  TEMP_SUFFIX: SCRATCH_TEMP_SUFFIX,
  applyRewrites,
  containsAllSymbols,
} = require("./lib/chunks.js");
const { findCarriers, listJsFiles } = require("./lib/locate.js");
const { assertVariantGroup, BOUND, DRIFTED, REMOVED, planCarrier } = require("./lib/plan.js");
const { assertReversible, patternSegments, templateSegments } = require("./lib/segments.js");
const { reverseRule } = require("./lib/reverse.js");

const SIGNATURES_PATH = path.join(__dirname, "signatures.json");
const FEATURE_ID = "durable-turns";

// Rollback snapshots for the commit loop. Distinct from writeCarrier's own
// baseline/temp scratch names (they sit beside the carrier and must not
// collide), and the ".durable-turns." infix keeps an interrupted run's
// leftovers out of the carrier screen.
const COMMIT_SNAPSHOT_SUFFIX = ".durable-turns.commit-snapshot.js";

// Fallback for a rule that omits expectedCarriers. Upstream ships the turn
// lifecycle twice (main-process chunk + webview chunk), so a rule that binds
// only one side is a silent half-apply; the loud failure below is decided
// against the per-rule declaration in the library, and this default is what
// keeps an older or hand-edited library honest. Documented in README.md.
const DEFAULT_EXPECTED_CARRIERS = 2;

// The carrier expectation is library data, not a patcher constant: a rule
// declares how many carriers it must bind (currently 5 rules x 2 carriers),
// so when upstream really does collapse the duplicate -- or grows a third
// copy -- the number is versioned with the signatures instead of becoming a
// false alarm baked into code. Absent means DEFAULT_EXPECTED_CARRIERS.
function expectedCarriersOf(rule) {
  const declared = rule.expectedCarriers;
  if (declared == null) return DEFAULT_EXPECTED_CARRIERS;
  if (!Number.isInteger(declared) || declared < 1) {
    throw new Error("durable-turns: rule " + rule.id + " declares expectedCarriers "
      + JSON.stringify(declared) + "; it must be a positive integer");
  }
  return declared;
}

// Markers the patch introduces. They double as runtime counters, which makes a
// suppression observable from the console instead of only inferable from logs.
const MARKERS = [
  "__dtMode",
  "__dtCascadeUserStopOnly",
  "__dtNoDiscardKill",
  "__dtDiscardMethod",
];

function loadLibrary(options = {}) {
  const file = options.signaturesPath ?? SIGNATURES_PATH;
  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error("durable-turns: cannot read signature library " + file + ": " + error.message);
  }
  if (parsed == null || typeof parsed !== "object" || !Array.isArray(parsed.rules) || parsed.rules.length === 0) {
    throw new Error("durable-turns: signature library " + file + " is malformed");
  }
  for (const rule of parsed.rules) {
    if (typeof rule.id !== "string" || !Array.isArray(rule.edits) || rule.edits.length === 0) {
      throw new Error("durable-turns: rule in " + file + " is malformed");
    }
    // The carrier expectation is validated at load time, next to the rule it
    // belongs to: a declared number that is not a positive integer is a data
    // error, not a drift condition, and must never be quietly floored to the
    // default (that is how a 0 or "2" turns the half-apply gate back off).
    expectedCarriersOf(rule);
    for (const edit of rule.edits) {
      // Load-time reversibility check: an edit whose patched side does not
      // retain every identifier the upstream side consumes can never be
      // reverted, and finding that out at revert time is too late.
      assertReversible(patternSegments(edit.find), templateSegments(edit.template), rule.id + "/" + edit.id);
    }
    // A variant group is all-or-nothing data. Half-tagging it silently
    // degrades the both-variants-bound and no-variant-bound checks at once,
    // so the shape of the group is a load-time invariant, not a plan-time one.
    assertVariantGroup(rule);
  }
  return parsed;
}

function summarise(plan) {
  return {
    rule: plan.ruleId,
    file: plan.file,
    status: plan.status,
    applied: plan.applied === true,
    edits: plan.rewrites.length + "/" + plan.editsTotal,
    variants: plan.variants && plan.variants.length > 0 ? plan.variants.join("/") : undefined,
    reason: plan.why ?? undefined,
  };
}

function formatExcerpt(plan) {
  if (plan.excerpt == null) return "";
  const caret = " ".repeat(Math.max(0, Math.min(plan.excerpt.caretColumn ?? 0, 3800))) + "^";
  return [
    "    region offset " + plan.excerpt.offset + " (caret marks the failed anchor)",
    "    " + plan.excerpt.text.replace(/\n/g, " "),
    "    " + caret,
  ].join("\n");
}

// Syntax gate. A rewrite is text spliced into working JavaScript, so the cheapest
// proof that it did not break the chunk is to let the parser look at the result.
// The check is self-calibrating: a chunk that already fails `node --check` in its
// pristine form (an ES module read as a script, for instance) is not evidence of
// anything, so only a pristine-passes / patched-fails transition is a failure.
function runNodeCheck(nodeExec, filePath) {
  let error;
  try {
    execFileSync(nodeExec, ["--check", filePath], { stdio: "pipe", maxBuffer: 4 * 1024 * 1024 });
    return { ok: true, detail: null };
  } catch (caught) {
    error = caught;
  }
  // A process that ran and exited non-zero reported a parse result. A process
  // that never ran (spawn ENOENT/EPERM, killed by a signal, stdout overflow)
  // reported nothing, and recording it as ok:false makes the gate read as
  // "upstream does not parse either", which silently switches it off. It throws
  // instead, and writeCarrier turns that into a restore plus a build failure.
  const status = typeof error.status === "number" ? error.status : null;
  const signal = error.signal == null ? null : error.signal;
  if (status == null || signal != null) {
    throw new Error("durable-turns: the syntax gate could not run " + nodeExec
      + " --check on " + filePath + " (" + String(error.code ?? error.name ?? "error")
      + (signal != null ? ", killed by " + signal : "") + ")"
      + "; refusing to patch with an unarmed gate");
  }
  return { ok: false, detail: String(error.stderr || error.message).split("\n").slice(0, 3).join(" | ") };
}

function verifySyntax(carrier, pristineCopy, nodeExec) {
  const baseline = runNodeCheck(nodeExec, pristineCopy);
  if (!baseline.ok) {
    // Calibrating the gate needs a baseline the parser accepts. Returning here
    // used to be the silent path; a gate that is quietly off is indistinguishable
    // from one that passed, so the carrier is refused instead.
    throw new Error("durable-turns: the syntax gate cannot calibrate on " + carrier.relPath
      + ": the pristine baseline does not pass `node --check` (" + baseline.detail + ")"
      + "; refusing to ship a chunk the parser never accepted");
  }
  const after = runNodeCheck(nodeExec, carrier.filePath);
  if (!after.ok) {
    throw new Error("durable-turns: patched " + carrier.relPath
      + " no longer parses (upstream did): " + after.detail);
  }
}

// Whether a rewrite actually moved bytes. An edit whose replacement equals the
// text it replaced is legitimate, and counting it as a change would make an
// already-patched tree look dirty.
function bytesDiffer(filePath, rewrites) {
  for (const rewrite of rewrites) {
    if (readAt(filePath, rewrite) !== rewrite.replacement) return true;
  }
  return false;
}

function readAt(filePath, rewrite) {
  const fd = fs.openSync(filePath, "r");
  try {
    const buffer = Buffer.alloc(rewrite.end - rewrite.start);
    fs.readSync(fd, buffer, 0, buffer.length, rewrite.start);
    return buffer.toString("latin1");
  } finally {
    fs.closeSync(fd);
  }
}

// Applies rewrites and gates the result on the parser, restoring the previous
// bytes if they do not parse. A gate that fires after the write would otherwise
// leave a broken chunk on disk for the next stage to package, which is the exact
// failure ciPolicy required-upstream exists to prevent.
function writeCarrier(carrier, rewrites, nodeExec) {
  if (rewrites.length === 0) return;
  // The suffix has to stay .js: the baseline goes through the same parser, and an
  // unknown extension makes node --check reject the file for the wrong reason, which
  // reads as "upstream did not parse either" and silently disables the gate.
  const backup = carrier.filePath + SCRATCH_BASELINE_SUFFIX;
  const temp = carrier.filePath + SCRATCH_TEMP_SUFFIX;
  // Leftovers from an interrupted run: a stale baseline ends in .js and holds the
  // whole contract, so it would be screened as a pseudo-carrier, and a stale temp
  // file would be packed into the published asar by the packaging stage.
  fs.rmSync(backup, { force: true });
  fs.rmSync(temp, { force: true });
  fs.copyFileSync(carrier.filePath, backup);
  const restore = () => {
    fs.copyFileSync(backup, carrier.filePath);
  };
  try {
    applyRewrites(carrier.filePath, rewrites);
    verifySyntax(carrier, backup, nodeExec);
  } catch (error) {
    restore();
    throw error;
  } finally {
    fs.rmSync(backup, { force: true });
    fs.rmSync(temp, { force: true });
  }
}

// Plans and, unless dry-run, writes every rule for one extracted bundle tree.
//
// A rule has to bind in every carrier: upstream ships the same turn-lifecycle
// logic twice, once per process side, and patching only one of them is a
// partial fix of exactly the kind that got shipped before.
function patchTree(extractedDir, options = {}) {
  const library = options.library ?? loadLibrary(options);
  const mode = options.mode ?? "apply";
  const dryRun = mode !== "apply";
  const nodeExec = options.nodeExec ?? process.execPath;
  const carriers = findCarriers(extractedDir, library);
  const report = {
    extractedDir,
    mode,
    carriers: carriers.map((carrier) => carrier.relPath),
    plans: [],
    changedFiles: [],
    failures: [],
  };
  // Carriers are planned first and written only after the tree-level audit
  // below passes, so every failure the planner can see -- an unbound rule, an
  // ambiguous region, an under-bound carrier count -- is decided before a
  // single byte moves.
  const staged = [];

  // Zero carriers is the loudest possible drift signal -- upstream rotated one of
  // the four contract symbols or moved the logic out of the scanned directories --
  // and it used to return here, which the descriptor mapped to already-applied and
  // both CI gates read as green. The entry now reaches the unified throw below.
  if (carriers.length === 0) {
    report.failures.push({
      rule: "(carrier)",
      file: null,
      status: REMOVED,
      reason: "no chunk under " + library.scan.dirs.join(", ") + " holds the turn-lifecycle contract",
    });
  }

  for (const carrier of carriers) {
    const planned = planCarrier(carrier, library.rules, library.scan, mode);
    for (const plan of planned.plans) report.plans.push(summarise(plan));
    for (const plan of planned.failed) {
      report.failures.push({
        rule: plan.ruleId,
        file: plan.file,
        status: plan.status,
        reason: plan.why ?? null,
        excerpt: plan.excerpt ?? null,
      });
    }

    if (planned.failed.length > 0) continue;
    if (planned.rewrites.length === 0) continue;

    // Stage, do not commit: every carrier is planned and the tree-level
    // audit runs first, so a rule that ends up under-bound -- or a syntax
    // gate that fires on the second carrier -- cannot leave the first
    // carrier rewritten on disk. Writing here produced a mixed tree that
    // only self-healed if someone thought to run a revert.
    staged.push({ carrier, rewrites: planned.rewrites });
  }

  // Half-apply gate. Every rule declares in the library how many carriers it
  // is expected to bind (expectedCarriers; DEFAULT_EXPECTED_CARRIERS when the
  // field is absent). Upstream ships the turn lifecycle twice, once per
  // process side, so a tree where only one side binds -- because the other
  // side's chunk was renamed out of the symbol screen, moved out of scan.dirs,
  // or deleted -- reports success in every per-carrier check and is exactly
  // the silent half-apply ciPolicy required-upstream forbids. The expectation
  // lives in the library (data, versioned with the signatures) rather than as
  // a hardcoded carriers >= 2 in the patcher, so that an upstream release
  // which really does collapse the duplicate is a one-line data change and not
  // a false build failure.
  auditCarrierCounts(report, library, extractedDir);

  if (!dryRun && report.failures.length > 0) {
    const detail = report.failures.map((failure) => {
      const where = failure.file == null ? failure.rule : failure.rule + " in " + failure.file;
      const lines = ["  " + failure.status + " " + where + ": " + failure.reason];
      const withExcerpt = plannedFor(report, failure);
      if (withExcerpt != null) lines.push(formatExcerpt(withExcerpt));
      return lines.join("\n");
    }).join("\n");
    throw new Error("durable-turns: refusing to ship a partial patch.\n" + detail);
  }

  // Commit phase. Everything the planner and the carrier audit could decide
  // was decided without a byte moving; what remains is the write loop itself.
  // It used to interleave with planning, so a failure on the second carrier
  // (the syntax gate firing mid-way is the realistic one) left the first
  // carrier patched and the second pristine -- a mixed tree that only
  // self-healed if somebody remembered to run a revert. Each write now takes
  // a snapshot under the .durable-turns. scratch namespace before touching
  // the carrier, and any commit failure restores every snapshot before
  // rethrowing, so the tree is all-patched or all-upstream.
  if (!dryRun) commitStaged(staged, report, nodeExec);

  return report;
}

function commitStaged(staged, report, nodeExec) {
  const snapshots = [];
  try {
    for (const { carrier, rewrites } of staged) {
      const snapshot = carrier.filePath + COMMIT_SNAPSHOT_SUFFIX;
      fs.rmSync(snapshot, { force: true });
      fs.copyFileSync(carrier.filePath, snapshot);
      snapshots.push({ carrier, snapshot });
      writeCarrier(carrier, rewrites, nodeExec);
      if (bytesDiffer(carrier.filePath, rewrites)) report.changedFiles.push(carrier.relPath);
    }
  } catch (error) {
    for (const { carrier, snapshot } of snapshots) {
      if (fs.existsSync(snapshot)) fs.copyFileSync(snapshot, carrier.filePath);
    }
    throw error;
  } finally {
    for (const { snapshot } of snapshots) fs.rmSync(snapshot, { force: true });
  }
}

// Compares each rule's BOUND carrier count against its declared expectation.
// Runs in every mode (check, dry-run, apply): a --check that stays green on a
// half-carrier tree would send the operator to the build to learn what the
// drift report already knew. The zero-carrier case is already recorded as a
// (carrier) REMOVED failure above, and this audit repeats it per rule so a
// rule-level report never reads "0 carriers" as a mystery.
function auditCarrierCounts(report, library, extractedDir) {
  report.notes = report.notes ?? [];
  const boundByRule = new Map();
  for (const plan of report.plans) {
    if (plan.status !== BOUND) continue;
    if (!boundByRule.has(plan.rule)) boundByRule.set(plan.rule, []);
    boundByRule.get(plan.rule).push(plan.file);
  }
  for (const rule of library.rules) {
    const expected = expectedCarriersOf(rule);
    const bound = boundByRule.get(rule.id) ?? [];
    if (bound.length === expected) continue;
    // Under-binding is only *unexplained* by the per-carrier failures when the
    // scan itself found fewer carriers than the rule needs: a carrier that was
    // screened but failed the rule already reports DRIFTED/REMOVED with its
    // file name and excerpt. A carrier that is not screened at all -- renamed,
    // moved, or its directory deleted -- produces no plan at all, and without
    // this audit the tree would look fine.
    if (bound.length < expected && report.carriers.length < expected) {
      report.failures.push({
        rule: rule.id,
        file: null,
        status: DRIFTED,
        reason: "expected " + expected + " carrier(s), bound " + bound.length
          + " [" + (bound.length === 0 ? "none" : bound.join(", ")) + "]"
          + "; " + carrierGapNote(extractedDir, library, report.carriers),
        excerpt: null,
      });
    } else if (bound.length > expected) {
      // Over-binding is diagnosis, not failure: an upstream release that
      // grows a third copy of the turn lifecycle is legitimate, and the build
      // must not die on it. The surplus is named in report.notes so --check
      // and --json leave something to audit.
      report.notes.push("rule " + rule.id + " bound " + bound.length
        + " carriers, more than the expected " + expected + ": " + bound.join(", "));
    }
  }
}

// Names the gap in symbols, which is the only way a half-vanished side can be
// described once its file name is no longer on disk to point at. The carrier
// contract is the symbol set, so the message recites the contract and the
// per-directory census: where the contract still holds, and in the case where
// a scanned directory has stopped producing a carrier, which contract symbols
// its chunks still hold (a rename of one symbol reads differently from the
// deletion of the directory, and the operator should not have to guess).
// This only runs on the failure path, so the census cost is bounded to trees
// that are already refusing to build.
function carrierGapNote(extractedDir, library, carriers) {
  const contract = library.carrierSymbols;
  const parts = ["carrier contract: every chunk holding " + contract.join(", ")
    + " must carry the rule"];
  const carrierSet = new Set(carriers);
  const census = [];
  for (const rel of library.scan.dirs) {
    const abs = path.join(extractedDir, rel);
    const files = listJsFiles(abs, library.scan.fileSuffix);
    const inDir = files.map((file) => path.relative(extractedDir, file));
    const hit = inDir.filter((r) => carrierSet.has(r));
    census.push(rel + ": " + inDir.length + " chunk(s), " + hit.length + " carrier(s)");
    if (hit.length === 0 && inDir.length > 0) {
      // The side that should hold a carrier produced none. Check whether any
      // of its chunks still speak part of the contract -- that distinguishes
      // "moved away" from "renamed in place" without naming a single file in
      // the signature library.
      const partials = [];
      for (const file of files) {
        const held = contract.filter((symbol) => containsAllSymbols(file, [symbol], library.scan));
        if (held.length > 0 && held.length < contract.length) {
          partials.push(path.relative(extractedDir, file) + " holds "
            + held.join(",") + " (missing " + contract.filter((s) => !held.includes(s)).join(",") + ")");
        }
      }
      if (partials.length > 0) parts.push("partial contract chunks in " + rel + ": " + partials.join(" ; "));
    }
  }
  parts.push("census: " + census.join(" | "));
  return parts.join("; ");
}

// Re-derives the excerpt for a failed rule so the CLI can print source, without
// keeping excerpts on every successful plan.
function plannedFor(report, failure) {
  if (failure.excerpt == null) return null;
  return { excerpt: failure.excerpt };
}

// Reverts every rule, back to the upstream bytes.
function reverseTree(extractedDir, options = {}) {
  const library = options.library ?? loadLibrary(options);
  const carriers = findCarriers(extractedDir, library);
  const report = { extractedDir, mode: "reverse", carriers: carriers.map((c) => c.relPath), plans: [], changedFiles: [], failures: [] };
  for (const carrier of carriers) {
    const rewrites = [];
    for (const rule of library.rules) {
      const plan = reverseRule(carrier, rule, library.scan);
      report.plans.push({ rule: rule.id, file: carrier.relPath, status: plan.status, applied: plan.applied === true, edits: plan.rewrites.length + "/" + rule.edits.length });
      if (plan.status !== BOUND) {
        report.failures.push({ rule: rule.id, file: carrier.relPath, status: plan.status, reason: plan.why ?? null });
        continue;
      }
      for (const rewrite of plan.rewrites) rewrites.push(rewrite);
    }
    if (report.failures.length > 0) continue;
    if (rewrites.length === 0) continue;
    if (options.mode !== "dry-run") {
      writeCarrier(carrier, rewrites, options.nodeExec ?? process.execPath);
      if (bytesDiffer(carrier.filePath, rewrites)) report.changedFiles.push(carrier.relPath);
    }
  }
  return report;
}

function formatReport(report) {
  const lines = [
    "durable-turns " + report.mode + " against " + report.extractedDir,
    "  carriers: " + (report.carriers.length > 0 ? report.carriers.join(", ") : "(none)"),
  ];
  for (const plan of report.plans) {
    lines.push("  " + pad(plan.status, 8) + plan.rule + "  " + plan.file + "  edits=" + plan.edits
      + (plan.variants ? "  variant=" + plan.variants : "")
      + (plan.applied ? "  (already applied)" : ""));
  }
  for (const failure of report.failures) {
    lines.push("  " + failure.status + " " + failure.rule + (failure.file ? " in " + failure.file : "") + ": " + failure.reason);
  }
  for (const note of report.notes ?? []) {
    lines.push("  NOTE " + note);
  }
  return lines.join("\n");
}

function pad(value, width) {
  const text = String(value);
  return text.length >= width ? text + " " : text + " ".repeat(width - text.length);
}

// The patch runs as one extracted-app descriptor rather than a main-bundle plus
// an asset descriptor, because both of those phases presuppose a file name and
// the whole point of the rewrite is that no file name is trusted any more.
function buildDescriptors(options = {}) {
  const library = options.library ?? loadLibrary(options);
  return [
    {
      id: "durable-turns",
      phase: "extracted-app:pre-webview",
      order: 20_700,
      ciPolicy: "required-upstream",
      missingDescription: "turn-lifecycle carrier chunk (interruptConversationSelf / discardConversationFromCache)",
      skipDescription: "durable-turns turn lifetime patch",
      targetSummary: "all-linux (symbol located, no bundle file name)",
      apply(extractedDir) {
        const report = patchTree(extractedDir, { library, mode: "apply" });
        if (report.carriers.length === 0) {
          throw new Error("durable-turns: no turn-lifecycle carrier in " + extractedDir);
        }
        const changed = report.changedFiles.length > 0;
        const applied = report.plans.filter((plan) => plan.status === BOUND && !plan.applied).length;
        console.log("durable-turns: " + applied + " edit(s) applied across " + report.carriers.length
          + " carrier(s) in " + path.basename(String(extractedDir)));
        return { changed, applied, carriers: report.carriers.length };
      },
      status(result) {
        if (result == null) return { status: "failed-required", reason: "durable-turns produced no result" };
        if (result.changed) return { status: "applied", reason: null };
        return { status: "already-applied", reason: null };
      },
    },
  ];
}

